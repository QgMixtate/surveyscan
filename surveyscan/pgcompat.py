"""Адаптер PostgreSQL с API, совместимым со sqlite3 (этап 1: перевод ядра на PostgreSQL).

Задача — перевести хранилище на PostgreSQL, не переписывая все запросы. Модули
продолжают вызывать con.execute("... ?", params), con.executemany, executescript,
commit; адаптер транслирует диалект SQLite → PostgreSQL на лету:

- плейсхолдеры ?           → %s
- datetime('now')          → now()
- INSERT OR REPLACE/IGNORE → INSERT ... ON CONFLICT DO NOTHING
- INTEGER PRIMARY KEY (DDL)→ INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
- ATTACH/DETACH DATABASE   → no-op (наборы данных живут схемами bdu/ms/adv в одной БД)

Исторически наборы данных лежали в отдельных файлах SQLite (survey/bdu/msrc/adv).
В PostgreSQL один «прогон обследования» = одна БД (имя выводится из общего каталога
путей), а наборы — это схемы: public (обследование), bdu, ms (MSRC), adv (фиды).
"""
from __future__ import annotations

import hashlib
import os
import re
from pathlib import Path

import psycopg

DSN = os.environ.get("SURVEYSCAN_PG_DSN", "host=127.0.0.1 port=5433 user=surveyscan")
MAINT_DB = os.environ.get("SURVEYSCAN_PG_MAINT", "surveyscan")


class Row(dict):
    """Строка результата: доступ и по имени (row['col']), и по индексу (row[0])."""
    __slots__ = ("_vals",)

    def __init__(self, cols, vals):
        super().__init__(zip(cols, vals))
        self._vals = list(vals)

    def __getitem__(self, k):
        if isinstance(k, int):
            return self._vals[k]
        return super().__getitem__(k)

    def __iter__(self):                 # как sqlite3.Row: перебор даёт значения
        return iter(self._vals)

    def keys(self):
        return list(super().keys())


def _row_factory(cursor):
    cols = [c.name for c in cursor.description] if cursor.description else []
    def make(values):
        return Row(cols, values)
    return make


_DDL_IDENTITY = re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\b", re.IGNORECASE)


def _translate(sql: str, ddl: bool = False) -> str:
    s = sql
    s = s.replace("datetime('now')", "now()")
    # GROUP_CONCAT([DISTINCT] expr) -> string_agg([DISTINCT] expr, ',')
    s = re.sub(r"GROUP_CONCAT\(\s*(DISTINCT\s+)?([^()]+?)\s*\)",
               r"string_agg(\1\2, ',')", s, flags=re.IGNORECASE)
    # INSERT OR REPLACE/IGNORE -> INSERT ... ON CONFLICT DO NOTHING
    m = re.search(r"INSERT\s+OR\s+(REPLACE|IGNORE)\s+INTO", s, re.IGNORECASE)
    if m:
        s = re.sub(r"INSERT\s+OR\s+(REPLACE|IGNORE)\s+INTO", "INSERT INTO", s, flags=re.IGNORECASE)
        if "ON CONFLICT" not in s.upper():
            s = s.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    if ddl:
        s = _DDL_IDENTITY.sub("INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s)
    # плейсхолдеры ? -> %s (в этом коде '?' не встречается в строковых литералах SQL)
    s = s.replace("?", "%s")
    return s


class _Cursor:
    def __init__(self, cur):
        self._cur = cur

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur)

    @property
    def description(self):
        return self._cur.description

    @property
    def lastrowid(self):               # совместимость; используйте RETURNING id
        return None


class PgConn:
    """Обёртка над psycopg-соединением с API в стиле sqlite3."""

    def __init__(self, conn):
        self._c = conn
        self._c.row_factory = _row_factory

    def execute(self, sql, params=()):
        up = sql.lstrip()[:7].upper()
        if up.startswith("ATTACH") or up.startswith("DETACH"):
            return _Cursor(self._c.cursor())      # no-op: наборы данных — это схемы
        cur = self._c.cursor()
        cur.execute(_translate(sql), tuple(params) if params else None)
        return _Cursor(cur)

    def executemany(self, sql, seq):
        cur = self._c.cursor()
        cur.executemany(_translate(sql), [tuple(x) for x in seq])
        return _Cursor(cur)

    def executescript(self, script):
        cur = self._c.cursor()
        for stmt in script.split(";"):
            if stmt.strip():
                cur.execute(_translate(stmt, ddl=True))
        return _Cursor(cur)

    def commit(self):
        self._c.commit()

    def rollback(self):
        self._c.rollback()

    def close(self):
        self._c.close()

    def set_search_path(self, *schemas):
        path = ", ".join(schemas) + ", public"
        self._c.cursor().execute(f"SET search_path TO {path}")
        self._c.commit()


# --------------------------------------------------------------------------- БД и схемы

def _dbname(path: Path) -> str:
    """Имя БД выводится из каталога набора путей — один прогон = одна БД."""
    key = str(Path(path).resolve().parent)
    return "ss_" + hashlib.sha1(key.encode()).hexdigest()[:16]


def _ensure_database(dbname: str) -> None:
    with psycopg.connect(f"{DSN} dbname={MAINT_DB}", autocommit=True) as m:
        exists = m.execute("SELECT 1 FROM pg_database WHERE datname = %s", (dbname,)).fetchone()
        if not exists:
            m.execute(f'CREATE DATABASE "{dbname}"')


def open_db(path: Path, schema: str = "public", recreate: bool = False) -> PgConn:
    """Открыть соединение к БД прогона (создав её при необходимости).

    recreate=True пересоздаёт схему набора данных (bdu/ms/adv) — импорт всегда свежий.
    """
    dbname = _dbname(path)
    _ensure_database(dbname)
    conn = psycopg.connect(f"{DSN} dbname={dbname}")
    pg = PgConn(conn)
    if recreate and schema != "public":
        c = conn.cursor()
        c.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
        c.execute(f'CREATE SCHEMA "{schema}"')
        conn.commit()
    if schema != "public":
        pg.set_search_path(schema)
    return pg


def drop_db(path: Path) -> None:
    """Удалить БД прогона (для чистого перезапуска demo по тому же каталогу)."""
    dbname = _dbname(path)
    with psycopg.connect(f"{DSN} dbname={MAINT_DB}", autocommit=True) as m:
        m.execute("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = %s", (dbname,))
        m.execute(f'DROP DATABASE IF EXISTS "{dbname}"')


def schema_exists(con: PgConn, name: str) -> bool:
    r = con.execute("SELECT 1 FROM information_schema.schemata WHERE schema_name = %s", (name,)).fetchone()
    return r is not None
